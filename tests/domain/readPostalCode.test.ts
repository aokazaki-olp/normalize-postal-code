import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { readPostalCode } from '../../src/domain/readPostalCode.ts';

describe('readPostalCode', () => {
  describe('数字がちょうど7個で、間に文字が無ければ読む', () => {
    const cases: [string, string][] = [
      ['ハイフン', '123-4567'],
      ['区切りなし', '1234567'],
      ['空白の区切り', '123 4567'],
      ['ドットの区切り', '123.4567'],
      ['括弧の区切り', '(123)4567'],
      ['長音符の区切り', '123ー4567'],
      ['マイナス記号の区切り', '123−4567'],
      ['ばらばらの区切り', '1 2 3 - 4 5 6 7'],
      ['前後の空白', '  123-4567  '],
      ['前の印', '〒123-4567'],
      ['重なった印', '郵便番号:〒123-4567'],
      ['後ろの文字', '〒123-4567 東京都'],
      ['前の文字', '自宅 123-4567'],
      ['括弧で囲んだ番号', '[123-4567]'],
    ];
    for (const [name, text] of cases) {
      it(name, () => {
        assert.equal(readPostalCode(text), '1234567');
      });
    }
  });

  describe('読まない', () => {
    const cases: [string, string][] = [
      ['数字が6個', '123-456'],
      ['数字が8個', '1234-5678'],
      ['旧番号の5桁', '123-45'],
      ['旧番号の3桁', '123'],
      ['後ろに番地の数字がある', '〒123-4567 東京都1-1'],
      ['間に漢字がある', '1丁目2番3号4567'],
      ['間に英字がある', '123A4567'],
      ['間にかながある', '123の4567'],
      ['間に丸数字がある', '123①4567'],
      ['デジタルアドレスの形', 'RS6-L5HS'],
      ['数字が無い', '東京都'],
      ['空', ''],
      ['ASCII 以外の数字', '١٢٣-٤٥٦٧'],
    ];
    for (const [name, text] of cases) {
      it(name, () => {
        assert.equal(readPostalCode(text), null);
      });
    }
  });
});
