import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { readPostalCode } from '../../src/domain/readPostalCode.ts';

describe('readPostalCode', () => {
  describe('数字がちょうど7個で、間に文字が無ければ読む', () => {
    const cases: [string, string, string, string][] = [
      ['ハイフン', '123-4567', '1234567', ''],
      ['区切りなし', '1234567', '1234567', ''],
      ['空白の区切り', '123 4567', '1234567', ''],
      ['ドットの区切り', '123.4567', '1234567', ''],
      ['括弧の区切り', '(123)4567', '1234567', ''],
      ['長音符の区切り', '123ー4567', '1234567', ''],
      ['マイナス記号の区切り', '123−4567', '1234567', ''],
      ['ばらばらの区切り', '1 2 3 - 4 5 6 7', '1234567', ''],
      ['前後の空白', '  123-4567  ', '1234567', ''],
      ['〒 の印は残りに入れない', '〒123-4567', '1234567', ''],
      ['〠 の印は残りに入れない', '〠123-4567', '1234567', ''],
      [
        '郵便番号の印とコロンは残りに入れない',
        '郵便番号: 123-4567',
        '1234567',
        '',
      ],
      ['後ろの文字は残りに入れる', '〒123-4567 東京都', '1234567', '東京都'],
      ['前の文字は残りに入れる', '自宅 123-4567', '1234567', '自宅'],
      [
        '前後の文字は空白でつなぐ',
        '自宅 123-4567 東京都',
        '1234567',
        '自宅 東京都',
      ],
      ['記号だけのかけらは残りに入れない', '[123-4567]', '1234567', ''],
      ['重なった印は残りに入れない', '郵便番号:〒123-4567', '1234567', ''],
      ['空白で区切った印', '郵便番号 〒 123-4567', '1234567', ''],
      ['括弧で囲んだ印', '【郵便番号】123-4567', '1234567', ''],
      ['印のあとの BMP 外の記号', '郵便番号🏣123-4567', '1234567', ''],
      ['印のあとのゼロ幅の空白', '郵便番号\u200B123-4567', '1234567', ''],
      [
        '印より前の文字は残りに入れる',
        '自宅 郵便番号:123-4567',
        '1234567',
        '自宅',
      ],
      ['括弧の中の文字は残りに入れる', '123-4567 (東京)', '1234567', '(東京)'],
    ];
    for (const [name, text, digits, unmatched] of cases) {
      it(name, () => {
        assert.deepEqual(readPostalCode(text), { digits, unmatched });
      });
    }
  });

  describe('読まない', () => {
    const cases: [string, string][] = [
      ['数字が6個', '123-456'],
      ['数字が8個', '1234-5678'],
      ['旧番号の5桁', '123-45'],
      ['旧番号の3桁', '123'],
      ['後ろに番地の数字がある', '〒123-4567 東京都1-1'],
      ['間に漢字がある', '1丁目2番3号4567'],
      ['間に英字がある', '123A4567'],
      ['間にかながある', '123の4567'],
      ['間に丸数字がある', '123①4567'],
      ['デジタルアドレスの形', 'RS6-L5HS'],
      ['数字が無い', '東京都'],
      ['空', ''],
    ];
    for (const [name, text] of cases) {
      it(name, () => {
        assert.deepEqual(readPostalCode(text), {
          digits: null,
          unmatched: text.trim(),
        });
      });
    }
  });

  it('印が長く並んでも時間が伸びない', () => {
    const started = performance.now();
    readPostalCode(`${'〒'.repeat(50000)}あ123-4567`);
    readPostalCode(`${'〒 '.repeat(50000)}あ123-4567`);
    assert.ok(performance.now() - started < 1000);
  });

  it('印の前の記号つきの文字は残す', () => {
    assert.deepEqual(readPostalCode('自宅:〒123-4567'), {
      digits: '1234567',
      unmatched: '自宅:',
    });
  });

  it('ASCII 以外の数字は数えない', () => {
    assert.equal(readPostalCode('١٢٣-٤٥٦٧').digits, null);
  });
});
